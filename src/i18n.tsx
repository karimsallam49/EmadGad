/** Resolve a cart item's display title/subtitle from its product id, in the active language */
export function itemDisplay(
  id: string,
  fallbackTitle: string,
  fallbackSub: string,
  t: (s: string) => string,
  num: (n: number) => string,
): { title: string; sub: string } {
  const tire = TIRES.find((x) => x.id === id);
  if (tire) return { title: `${t('إطار')} ${tire.brand} ${tire.model}`, sub: tire.size };
  const bat = BATTERIES.find((x) => x.id === id);
  if (bat) return { title: `${t('بطارية')} ${bat.brand} ${bat.model}`, sub: `${num(bat.ah)} ${t('أمبير')}` };
  return { title: fallbackTitle, sub: fallbackSub };
}

const Ctx = createContext<LangValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() =>
    typeof localStorage !== 'undefined' && localStorage.getItem('emadgad-lang') === 'en' ? 'en' : 'ar',
  );

  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.title =
      lang === 'ar'
        ? 'EmadGad | إطارات وبطاريات وخدمات سيارات سريعة في مصر'
        : 'EmadGad | Tires, Batteries & Fast Car Services in Egypt';
    try {
      localStorage.setItem('emadgad-lang', lang);
    } catch {
      /* private mode */
    }
  }, [lang]);

  const value: LangValue = {
    lang,
    isAr: lang === 'ar',
    setLang,
    toggle: () => setLang((l) => (l === 'ar' ? 'en' : 'ar')),
    t: (s) => (lang === 'ar' ? s : (DICT[s] ?? s)),
    fmt: (n) => {
      const v = Number(n);
      return Number.isFinite(v)
        ? lang === 'ar' ? `${v.toLocaleString('ar-EG')} جنيه` : `EGP ${v.toLocaleString('en-US')}`
        : '';
    },
    num: (n) => {
      const v = Number(n);
      return Number.isFinite(v) ? v.toLocaleString(lang === 'ar' ? 'ar-EG' : 'en-US') : '';
    },
  };

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang(): LangValue {
  const v = useContext(Ctx);
  if (!v) throw new Error('useLang must be used inside LanguageProvider');
  return v;
}
